window.currentLang = localStorage.getItem('microcrm_lang') || navigator.language.slice(0, 2);
if(!translations[window.currentLang]) window.currentLang = 'en';

window.t = function(key) {
  return translations[window.currentLang][key] || key;
};

window.getCurrencyFormatter = function() {
  const map = { 
    pt: ['pt-BR', 'BRL'], en: ['en-US', 'USD'], es: ['es-ES', 'EUR'], 
    fr: ['fr-FR', 'EUR'], de: ['de-DE', 'EUR'], ru: ['ru-RU', 'RUB'], zh: ['zh-CN', 'CNY']
  };
  const data = map[window.currentLang] || map['en'];
  return new Intl.NumberFormat(data[0], { style: "currency", currency: data[1] });
};

function applyTranslations() {
  document.documentElement.lang = window.currentLang;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    el.innerHTML = t(el.getAttribute('data-i18n'));
  });
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    el.placeholder = t(el.getAttribute('data-i18n-ph'));
  });
  const langSelect = document.getElementById('langSelect');
  if (langSelect) langSelect.value = window.currentLang;
}

document.addEventListener('DOMContentLoaded', () => {
  applyTranslations();
  const langSelect = document.getElementById('langSelect');
  if (langSelect) {
    langSelect.addEventListener('change', (e) => {
      localStorage.setItem('microcrm_lang', e.target.value);
      window.location.reload(); // Recarrega para aplicar ao app.js
    });
  }
});